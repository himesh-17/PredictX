import React from "react";
import {
  AlertTriangle,
  CheckCircle,
  Clock,
  Database,
  Flame,
  Info,
  ShieldAlert,
  Zap,
} from "lucide-react";
import { AIPredictionResult, ReadingAssessmentResult, SensorReading } from "../types";

interface StatusOverviewProps {
  latestReading: SensorReading | null;
  standardsAssessment: ReadingAssessmentResult | null;
  aiPrediction: AIPredictionResult | null;
  activeAlertCount: number;
  activeDisturbance: string;
  disturbanceSeconds: number;
  onInjectDisturbance: (type: string, durationSec?: number) => void;
}

export const StatusOverview: React.FC<StatusOverviewProps> = ({
  latestReading,
  standardsAssessment,
  aiPrediction,
  activeAlertCount,
  activeDisturbance,
  disturbanceSeconds,
  onInjectDisturbance,
}) => {
  // Derive overall condition
  let overallCondition = "NORMAL";
  let statusColor = "text-[#34D399] border-[#34D399]/30 bg-[#34D399]/10";
  let StatusIcon = CheckCircle;

  if (!latestReading) {
    overallCondition = "NO_DATA";
    statusColor = "text-[#94A3B8] border-[#94A3B8]/30 bg-[#172338]";
    StatusIcon = Info;
  } else if (standardsAssessment?.overallStatus === "OUT_OF_LIMIT") {
    overallCondition = "OUT_OF_LIMIT";
    statusColor = "text-[#F87171] border-[#F87171]/40 bg-[#F87171]/15 glow-red";
    StatusIcon = ShieldAlert;
  } else if (standardsAssessment?.overallStatus === "WARNING") {
    overallCondition = "WARNING";
    statusColor = "text-[#FBBF24] border-[#FBBF24]/40 bg-[#FBBF24]/15 glow-amber";
    StatusIcon = AlertTriangle;
  } else if (aiPrediction?.status === "ANOMALY") {
    overallCondition = "ANOMALY";
    statusColor = "text-[#F87171] border-[#F87171]/40 bg-[#F87171]/15 glow-red";
    StatusIcon = AlertTriangle;
  }

  return (
    <div className="space-y-4">
      {/* Persistent Simulation Warning Banner */}
      <div className="flex flex-col sm:flex-row items-center justify-between gap-3 rounded-lg border border-[#FBBF24]/40 bg-[#FBBF24]/10 px-4 py-2.5 text-xs text-[#FBBF24]">
        <div className="flex items-center gap-2">
          <Info className="h-4 w-4 shrink-0" />
          <span className="font-semibold tracking-wide">
            SIMULATED DATA — NOT CONNECTED TO PHYSICAL HARDWARE (ESP32 Integration Pending)
          </span>
        </div>
        <span className="text-[11px] text-[#FBBF24]/80">
          Sensor streams and disturbances generated by realistic backend physics engine.
        </span>
      </div>

      {/* Main KPI Grid */}
      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
        {/* Card 1: Machine Condition */}
        <div className={`rounded-xl border p-4 transition-all ${statusColor}`}>
          <div className="flex items-center justify-between">
            <span className="text-xs font-medium uppercase tracking-wider text-[#94A3B8]">
              Overall Machine State
            </span>
            <StatusIcon className="h-5 w-5" />
          </div>
          <div className="mt-2 text-2xl font-bold tracking-tight">
            {overallCondition}
          </div>
          <div className="mt-1 text-xs opacity-80">
            {standardsAssessment?.overallStatus === "OUT_OF_LIMIT"
              ? "Exceeds configured engineering limits"
              : standardsAssessment?.overallStatus === "WARNING"
              ? "Approaching configured limit threshold"
              : "Operating within normal parameters"}
          </div>
        </div>

        {/* Card 2: Active Alerts */}
        <div className="rounded-xl border border-[#1E293B] bg-[#111B2E] p-4">
          <div className="flex items-center justify-between">
            <span className="text-xs font-medium uppercase tracking-wider text-[#94A3B8]">
              Active Alerts
            </span>
            <AlertTriangle className={`h-5 w-5 ${activeAlertCount > 0 ? "text-[#FBBF24]" : "text-[#94A3B8]"}`} />
          </div>
          <div className="mt-2 text-2xl font-bold font-mono text-[#F1F5F9]">
            {activeAlertCount}
          </div>
          <div className="mt-1 text-xs text-[#94A3B8]">
            {activeAlertCount === 0 ? "No active unacknowledged alerts" : "Requires engineer attention"}
          </div>
        </div>

        {/* Card 3: AI Model Contract Status */}
        <div className="rounded-xl border border-[#1E293B] bg-[#111B2E] p-4">
          <div className="flex items-center justify-between">
            <span className="text-xs font-medium uppercase tracking-wider text-[#94A3B8]">
              AI Model Input Schema
            </span>
            <Zap className="h-5 w-5 text-[#22D3EE]" />
          </div>
          <div className="mt-2 text-sm font-semibold font-mono text-[#22D3EE] truncate">
            {aiPrediction?.status || "CHECKING..."}
          </div>
          <div className="mt-1 text-xs text-[#94A3B8] truncate">
            {aiPrediction?.status === "MODEL_INPUT_INCOMPATIBLE"
              ? "Missing Accelerometer2RMS & Thermocouple"
              : "Isolation Forest active"}
          </div>
        </div>

        {/* Card 4: Operating Disturbance Mode */}
        <div className="rounded-xl border border-[#1E293B] bg-[#111B2E] p-4">
          <div className="flex items-center justify-between">
            <span className="text-xs font-medium uppercase tracking-wider text-[#94A3B8]">
              Synthetic Disturbance
            </span>
            <Flame className={`h-5 w-5 ${activeDisturbance !== "NONE" ? "text-[#F87171] animate-pulse" : "text-[#94A3B8]"}`} />
          </div>
          <div className="mt-2 text-sm font-mono font-bold text-[#F1F5F9]">
            {activeDisturbance}
            {disturbanceSeconds > 0 && (
              <span className="ml-1.5 text-xs font-normal text-[#FBBF24]">
                ({disturbanceSeconds}s)
              </span>
            )}
          </div>
          <div className="mt-1 text-xs text-[#94A3B8]">
            {activeDisturbance === "NONE" ? "Nominal baseline operation" : "Active synthetic anomaly"}
          </div>
        </div>
      </div>

      {/* Disturbance Injection Toolbar */}
      <div className="flex flex-wrap items-center justify-between gap-3 rounded-lg border border-[#1E293B] bg-[#111B2E] px-4 py-3">
        <div className="flex items-center gap-2">
          <span className="text-xs font-semibold text-[#94A3B8] uppercase tracking-wider">
            Test Disturbance Injection:
          </span>
          <span className="text-[11px] text-[#94A3B8] hidden md:inline">
            (Triggers realistic telemetry anomalies for dashboard verification)
          </span>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <button
            onClick={() => onInjectDisturbance("OVERHEATING", 25)}
            className="rounded bg-[#172338] border border-[#1E293B] px-2.5 py-1 text-xs font-medium text-[#F87171] hover:border-[#F87171]/50 hover:bg-[#F87171]/10 transition-all"
          >
            Overheating (92°C)
          </button>
          <button
            onClick={() => onInjectDisturbance("CURRENT_SURGE", 20)}
            className="rounded bg-[#172338] border border-[#1E293B] px-2.5 py-1 text-xs font-medium text-[#FBBF24] hover:border-[#FBBF24]/50 hover:bg-[#FBBF24]/10 transition-all"
          >
            Current Surge (5.3A)
          </button>
          <button
            onClick={() => onInjectDisturbance("HIGH_VIBRATION", 20)}
            className="rounded bg-[#172338] border border-[#1E293B] px-2.5 py-1 text-xs font-medium text-[#22D3EE] hover:border-[#22D3EE]/50 hover:bg-[#22D3EE]/10 transition-all"
          >
            High Vibration (0.55g)
          </button>
          <button
            onClick={() => onInjectDisturbance("VOLTAGE_SAG", 20)}
            className="rounded bg-[#172338] border border-[#1E293B] px-2.5 py-1 text-xs font-medium text-[#60A5FA] hover:border-[#60A5FA]/50 hover:bg-[#60A5FA]/10 transition-all"
          >
            Voltage Sag (198V)
          </button>
          {activeDisturbance !== "NONE" && (
            <button
              onClick={() => onInjectDisturbance("NONE", 0)}
              className="rounded bg-[#34D399]/20 border border-[#34D399]/50 px-2.5 py-1 text-xs font-medium text-[#34D399] hover:bg-[#34D399]/30 transition-all"
            >
              Reset to Normal
            </button>
          )}
        </div>
      </div>
    </div>
  );
};
